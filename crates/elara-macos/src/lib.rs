/// The modifier keys held during a key event.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub struct KeyModifiers {
    pub control: bool,
    pub shift: bool,
    pub option: bool,
    pub command: bool,
}

/// A key press or release, as seen before any application gets it.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct KeyEvent {
    /// The macOS virtual key code, which names a physical key regardless of keyboard layout.
    pub keycode: u16,
    /// What the key types on the current keyboard layout with no modifiers held, if it types
    /// anything.
    pub character: Option<char>,
    pub modifiers: KeyModifiers,
    /// `true` for a press, `false` for a release.
    pub pressed: bool,
    /// Whether this press was generated by holding the key down.
    pub is_repeat: bool,
}

/// Where a scroll is in the sequence of events that one gesture produces.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ScrollPhase {
    /// The device does not report gestures. A mouse wheel never does.
    None,
    /// Fingers touched down and started moving.
    Began,
    /// Fingers are moving.
    Changed,
    /// Fingers lifted, or the gesture was cancelled.
    Ended,
}

/// A scroll from a trackpad or a mouse wheel, as seen before any application gets it.
///
/// Positive `delta_x` moves content to the right and positive `delta_y` moves it down, which
/// already takes the user's "natural scrolling" setting into account.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ScrollEvent {
    pub delta_x: f64,
    pub delta_y: f64,
    /// `true` for a trackpad or other device that scrolls by points, in which case the deltas
    /// are in points. `false` for a wheel that scrolls in steps, in which case they are in
    /// steps.
    pub continuous: bool,
    pub phase: ScrollPhase,
    /// Whether this is the system letting the content coast after the fingers lifted.
    pub momentum: bool,
    pub modifiers: KeyModifiers,
}

/// A mouse button the input tap reports.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum MouseButton {
    Left,
    Right,
    Middle,
    /// The side button that goes back in a browser.
    Back,
    /// The side button that goes forward in a browser.
    Forward,
}

/// What happened to the mouse.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MouseEventKind {
    /// The button went down.
    Pressed(MouseButton),
    /// The button came up.
    Released(MouseButton),
    /// The pointer moved with a button held.
    Dragged,
}

/// A mouse button press, release or drag, as seen before any application gets it.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct MouseEvent {
    pub kind: MouseEventKind,
    /// Where the pointer is, in the global coordinates window frames use.
    pub position: Point,
    pub modifiers: KeyModifiers,
}

/// A key, scroll or mouse event from the input tap.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum InputEvent {
    Key(KeyEvent),
    Scroll(ScrollEvent),
    Mouse(MouseEvent),
}

/// A shape drawn on top of the desktop: a line around a rectangle, or a filled rectangle.
///
/// This is how focus rings, window borders and the hint for where a dragged window will land
/// get on screen.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Outline {
    /// The outer edge of the shape, in global coordinates.
    pub rect: Rect,
    /// How wide the line is, measured inwards from `rect`. Zero fills the whole rectangle.
    pub line_width: f64,
    /// How round the outer corners are: top-left, top-right, bottom-right, bottom-left.
    pub corner_radius: [f64; 4],
    /// Red, green, blue and opacity, each from 0 to 1. The colors are sRGB and are not
    /// multiplied by the opacity.
    pub color: [f32; 4],
}

/// The overview: every workspace and its windows, zoomed out.
///
/// macOS does not let a window manager shrink another application's windows. So the overview
/// is a picture: it covers each display, and on it every window is drawn as a card, in the
/// place and at the size the zoomed-out window would have. The real windows stay where they
/// are, underneath.
#[derive(Debug, Clone, PartialEq, Default)]
pub struct Overview {
    /// What shows behind the workspaces: red, green, blue and opacity, as in [`Outline`].
    pub backdrop: [f32; 4],
    /// Whether to show a picture of each window in place of its card, and how large to take
    /// the pictures: this many times the size of the window. Taking them needs the Screen
    /// Recording permission; a window there is no picture of keeps its card.
    pub thumbnails: Option<f64>,
    /// What to draw on each display. A display that is not listed shows only the backdrop.
    pub displays: Vec<OverviewDisplay>,
}

/// The part of the overview that one display shows. All coordinates are global.
#[derive(Debug, Clone, PartialEq)]
pub struct OverviewDisplay {
    pub display: DisplayId,
    /// The workspaces, drawn under everything else.
    pub workspaces: Vec<OverviewWorkspace>,
    /// Windows and what niri draws around them. Later ones are drawn over earlier ones.
    pub items: Vec<OverviewItem>,
}

/// A workspace in the overview: a rectangle the shape of the display.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct OverviewWorkspace {
    pub rect: Rect,
    pub color: [f32; 4],
    pub shadow: Option<OverviewShadow>,
}

/// The shadow a workspace casts on the backdrop.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct OverviewShadow {
    /// How far the shadow is shifted, to the right and down.
    pub offset: (f64, f64),
    /// How far the shadow fades out past its edge.
    pub softness: f64,
    pub color: [f32; 4],
}

/// Something drawn on top of the workspaces of the overview.
#[derive(Debug, Clone, PartialEq)]
pub enum OverviewItem {
    Window(OverviewWindow),
    /// A focus ring, a border, a tab or the insert hint, zoomed out like the windows.
    Shape(Outline),
}

/// A window in the overview.
#[derive(Debug, Clone, PartialEq)]
pub struct OverviewWindow {
    pub id: WindowId,
    /// Where the zoomed-out window is.
    pub rect: Rect,
    /// How round its corners are: top-left, top-right, bottom-right, bottom-left.
    pub corner_radius: [f64; 4],
    pub title: Option<String>,
}

/// What the user did on the overview, which is a window of ElaraWM's own and gets its mouse
/// events the ordinary way and not through the input tap.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum OverviewInput {
    Mouse(MouseEvent),
    /// A scroll, and where the pointer was, in global coordinates.
    Scroll(ScrollEvent, Point),
}

/// Identifies a window for as long as it exists. Never reused within one backend.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct WindowId(pub u64);

/// Identifies a display. On macOS this is the `CGDirectDisplayID`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct DisplayId(pub u32);

/// A connected display.
#[derive(Debug, Clone, PartialEq)]
pub struct DisplayInfo {
    pub id: DisplayId,
    /// Human-readable name, such as "Built-in Retina Display".
    pub name: String,
    /// The whole display.
    pub frame: Rect,
    /// The part of the display not covered by the menu bar and the Dock.
    pub visible_frame: Rect,
    /// Pixels per point.
    pub scale: f64,
    /// Refresh rate in millihertz, if known.
    pub refresh_mhz: Option<u32>,
    /// Whether this is the display with the menu bar.
    pub is_primary: bool,
}

/// What sort of window this is, which decides how it is managed.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum WindowKind {
    /// An ordinary document or application window. Tiled by default.
    Standard,
    /// A dialog, sheet or panel. Floats by default.
    Dialog,
    /// Anything else an application exposes as a window, such as a popover or a tooltip. Not
    /// managed.
    Other,
}

/// A window as last reported by its application.
#[derive(Debug, Clone, PartialEq)]
pub struct WindowInfo {
    pub id: WindowId,
    /// Process that owns the window.
    pub pid: i32,
    /// Bundle identifier of the owning application, such as "com.apple.Terminal".
    pub app_id: Option<String>,
    pub title: Option<String>,
    pub frame: Rect,
    pub kind: WindowKind,
    /// Whether the application lets the window be resized.
    pub resizable: bool,
    /// Whether the application lets the window be moved.
    pub movable: bool,
    pub minimized: bool,
    /// Whether the window is in macOS native fullscreen, on a Space of its own.
    pub fullscreen: bool,
    /// Whether the window is on a macOS Space other than the one ElaraWM manages.
    pub on_other_space: bool,
}

/// Something that happened to a window or display since events were last drained.
#[derive(Debug, Clone, PartialEq)]
pub enum Event {
    /// A window appeared.
    WindowOpened(WindowInfo),
    /// A window is gone.
    WindowClosed(WindowId),
    /// A window was moved or resized, by the user, its application, or ElaraWM itself.
    WindowFrameChanged(WindowId, Rect),
    WindowTitleChanged(WindowId, Option<String>),
    /// A window was minimized (`true`) or restored (`false`). Hiding an application minimizes
    /// all of its windows in this sense.
    WindowMinimized(WindowId, bool),
    /// A window entered (`true`) or left (`false`) native fullscreen.
    WindowFullscreen(WindowId, bool),
    /// A window turned out to be on another macOS Space than the one ElaraWM manages
    /// (`true`), or showed up on that one (`false`).
    WindowOnOtherSpace(WindowId, bool),
    /// Keyboard focus moved to this window, or to nothing that is tracked.
    FocusChanged(Option<WindowId>),
    /// Displays were connected, disconnected, rearranged or reconfigured.
    DisplaysChanged,
}

/// Why a request to a window failed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Error {
    /// The window no longer exists.
    NoSuchWindow(WindowId),
    /// ElaraWM has not been granted the Accessibility permission.
    NotTrusted,
    /// The application did not answer in time, or refused.
    Unresponsive { window: WindowId, code: i32 },
}

impl fmt::Display for Error {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Error::NoSuchWindow(id) => write!(f, "window {} no longer exists", id.0),
            Error::NotTrusted => write!(f, "the Accessibility permission has not been granted"),
            Error::Unresponsive { window, code } => write!(
                f,
                "the application owning window {} did not carry out the request (AXError {code})",
                window.0
            ),
        }
    }
}

impl std::error::Error for Error {}

/// The operations a window manager needs from the system.
pub trait WindowBackend {
    /// Lists the connected displays, primary first.
    fn displays(&self) -> Vec<DisplayInfo>;

    /// Lists every window currently known, in no particular order.
    fn windows(&self) -> Vec<WindowInfo>;

    /// Returns the frame a window has now, as far as is known.
    fn window_frame(&self, window: WindowId) -> Option<Rect>;

    /// Returns the window that has keyboard focus, if it is a known window.
    fn focused_window(&self) -> Option<WindowId>;

    /// Asks a window to occupy `frame`.
    ///
    /// Returns the frame the window actually took. Applications may refuse a size, for example
    /// below their minimum, so the result can differ from the request.
    fn set_frame(&mut self, window: WindowId, frame: Rect) -> Result<Rect, Error>;

    /// Gives a window keyboard focus and raises it.
    fn focus(&mut self, window: WindowId) -> Result<(), Error>;

    /// Asks a window to close, as if its close button was pressed. The application may prompt.
    fn close(&mut self, window: WindowId) -> Result<(), Error>;

    /// Returns what happened since the last call, oldest first.
    fn drain_events(&mut self) -> Vec<Event>;

    /// Whether the user is looking at the macOS Space ElaraWM manages, which is the one that
    /// was showing when it started. While they are looking at another, nothing ElaraWM
    /// manages is in front of them.
    fn home_space_active(&self) -> bool {
        true
    }

    /// Shows exactly these outlines on top of the desktop, replacing whatever was shown.
    /// Later ones are drawn over earlier ones.
    fn set_outlines(&mut self, outlines: &[Outline]);

    /// Shows the overview, replacing what it showed before, or takes it away with `None`.
    fn set_overview(&mut self, overview: Option<&Overview>);
}
